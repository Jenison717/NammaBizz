    function normalize(text){
      return String(text||"").toLowerCase()
        .replace(/[’‘`]/g,"'")
        .replace(/[^a-z0-9\u0B80-\u0BFF\s]/g," ")
        .replace(/\s+/g," ").trim();
    }
    function words(text){return new Set(normalize(text).split(" ").filter(Boolean))}
    function hasAny(text, list){
      const n=normalize(text);
      return list.some(x=>n.includes(normalize(x)));
    }
    function detectDomain(q){
      const text=normalize(q);
      let ranked=Object.entries(domainKeywords).map(([domain,keys])=>{
        const hits=keys.filter(k=>text.includes(normalize(k)));
        return {domain,hits,count:hits.length};
      }).sort((a,b)=>b.count-a.count);
      return ranked[0].count?ranked[0]:{domain:null,hits:[],count:0};
    }
    function extractQuantity(q){
      const n=normalize(q);
      const m=n.match(/\b(\d+(?:\.\d+)?)\s*(pieces?|pcs?|units?|kg|kgs|kilograms?|g|grams?|tonnes?|tons?|boxes?|cartons?|bags?|dozen|dozens?)?\b/i);
      return m ? (m[1]+" "+(m[2]||"units")).trim() : "Not specified";
    }
    function extractProductTerms(q){
      const n=normalize(q);
      const terms=[];
      Object.values(synonyms).forEach(group=>{
        if(group.some(x=>n.includes(normalize(x)))) terms.push(group[0]);
      });
      return [...new Set(terms)];
    }
    function levenshtein(a,b){
      if(a===b)return 0;if(!a.length)return b.length;if(!b.length)return a.length;
      let prev=Array.from({length:b.length+1},(_,i)=>i);
      for(let i=0;i<a.length;i++){
        let cur=[i+1];
        for(let j=0;j<b.length;j++) cur.push(Math.min(cur[j]+1,prev[j+1]+1,prev[j]+(a[i]===b[j]?0:1)));
        prev=cur;
      }
      return prev[b.length];
    }
    function closeWordMatch(queryToken, candidate){
      if(queryToken.length<4 || candidate.length<4)return false;
      return candidate.split(" ").some(c=>c.length>=4 && levenshtein(queryToken,c)<=1);
    }
    function aiMatch(query){
      const q=normalize(query);
      const detected=detectDomain(q);
      const requestedProducts=extractProductTerms(q);
      const wantsWholesale=hasAny(q,synonyms.wholesale);
      const wantsMadurai=hasAny(q,["madurai","?????"]);
      const quantity=extractQuantity(q);

      const scored=businesses.map(b=>{
        let score=0, reasons=[];
        const profile=normalize([b.category,...b.products,...b.tags].join(" "));
        const tokens=[...words(q)].filter(t=>t.length>=3);
        const productHits=requestedProducts.filter(p=>b.products.some(x=>normalize(x).includes(p)||p.includes(normalize(x))));
        const directHits=tokens.filter(t=>profile.includes(t));
        const fuzzyHits=tokens.filter(t=>[...words(profile)].some(c=>closeWordMatch(t,c)));

        if(detected.domain===b.category){score+=45;reasons.push("Domain matches");}
        score+=Math.min(30,productHits.length*15);
        if(productHits.length) reasons.push("Product matches");
        score+=Math.min(12,directHits.length*2);
        if(fuzzyHits.length) score+=Math.min(5,fuzzyHits.length);
        if(wantsWholesale){score+=8;reasons.push("Wholesale requirement");}
        if(wantsMadurai){score+=5;reasons.push("Madurai location");}
        score=Math.min(99,score);

        if(!reasons.length) reasons.push("General business relevance");
        return {...b,score,match:score+"%",reasons,productHits};
      }).sort((a,b)=>b.score-a.score);

      // A meaningful query should not show unrelated businesses as if they were strong matches.
      let results=scored.filter(b=>b.score>=35);
      if(detected.count===0 && requestedProducts.length===0){
        results=scored.filter(b=>b.score>=15);
      }
      if(!results.length){
        return {results:[],detected,requestedProducts,quantity,wantsWholesale,wantsMadurai,noMatch:true};
      }
      return {results,detected,requestedProducts,quantity,wantsWholesale,wantsMadurai,noMatch:false};
    }

