        function distanceFromUser(business){
            if(!userLocation || !Number.isFinite(Number(business.latitude)) || !Number.isFinite(Number(business.longitude)))return "";
            const toRadians=value=>value*Math.PI/180;
            const earthRadius=6371;
            const dLat=toRadians(Number(business.latitude)-userLocation.latitude);
            const dLon=toRadians(Number(business.longitude)-userLocation.longitude);
            const lat1=toRadians(userLocation.latitude);
            const lat2=toRadians(Number(business.latitude));
            const a=Math.sin(dLat/2)**2+Math.cos(lat1)*Math.cos(lat2)*Math.sin(dLon/2)**2;
            const distance=earthRadius*2*Math.atan2(Math.sqrt(a),Math.sqrt(1-a));
            return distance<1 ? `${Math.round(distance*1000)} m away` : `${distance.toFixed(1)} km away`;
        }
